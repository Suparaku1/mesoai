const sq = { ...coreSq, ...academicSq, ...adminSq, ...commSq };
const en = { ...coreEn, ...academicEn, ...adminEn, ...commEn };
const it = { ...coreIt, ...academicIt, ...adminIt, ...commIt };
const de = { ...coreDe, ...academicDe, ...adminDe, ...commDe };

const dict: Record<Locale, Partial<Record<keyof typeof sq, string>>> = { sq, en, it, de };

export type TranslationKey = keyof typeof sq;

type TParams = Record<string, string | number>;

function interpolate(template: string, params?: TParams) {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (m, k) => (k in params ? String(params[k]) : m));
}

type Ctx = { locale: Locale; setLocale: (l: Locale) => void; t: (key: TranslationKey, params?: TParams) => string };

const I18nContext = createContext<Ctx | null>(null);

function isLocale(value: string | null): value is Locale {
  return !!value && (LOCALES as readonly string[]).includes(value);
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("sq");

  useEffect(() => {
    if (typeof window === "undefined") return;
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (isLocale(stored)) setLocaleState(stored);
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    if (typeof window !== "undefined") {
      window.localStorage.setItem(STORAGE_KEY, l);
      document.documentElement.lang = l;
    }
  }, []);

  const t = useCallback(
    (key: TranslationKey, params?: TParams) => interpolate(dict[locale][key] ?? sq[key] ?? key, params),
    [locale],
  );

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext);
  if (!ctx) return { locale: "sq", setLocale: () => {}, t: (k, p) => interpolate(sq[k] ?? k, p) };
  return ctx;
}
